// Builds ONE file you can paste into the Supabase SQL editor (no CLI needed):
//   npm run bundle:sql   ->  supabase/.bundle/schema.sql (all migrations, in order)  +  supabase/.bundle/seed.sql
// Run schema.sql first, then seed.sql. Both are generated, gitignored and safe to regenerate.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'

const files = readdirSync('supabase/migrations')
  .filter((f) => f.endsWith('.sql'))
  .sort()
const header = (what: string) =>
  `-- LAIRON EZ — ${what}\n-- Generated by scripts/bundle-sql.ts from supabase/migrations. Do not edit; regenerate instead.\n-- Run this ONCE on an EMPTY Supabase project.\n\n`
mkdirSync('supabase/.bundle', { recursive: true })
writeFileSync(
  'supabase/.bundle/schema.sql',
  header(`schema (${files.length} migrations)`) +
    files
      .map(
        (f) => `-- ───────── ${f} ─────────\n${readFileSync(`supabase/migrations/${f}`, 'utf8')}`,
      )
      .join('\n\n'),
)
writeFileSync(
  'supabase/.bundle/seed.sql',
  header('seed data (dropdowns, divisions, products, fleet placeholders, settings)') +
    readFileSync('supabase/seed.sql', 'utf8'),
)
console.log(
  `wrote supabase/.bundle/schema.sql (${files.length} migrations) and supabase/.bundle/seed.sql`,
)
